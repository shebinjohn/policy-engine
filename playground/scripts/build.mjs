// Builds the playground into one self-contained page: dist/policy-playground.html.
//
// 1. Generates src/ui/generated/content.ts, which imports every scenarios/*.json (sorted by
//    `order`) and challenges/*.json (sorted by `level`).
// 2. Bundles src/ui/main.tsx with esbuild. react, react-dom and ethers stay external and resolve to
//    the UMD globals React, ReactDOM and ethers, loaded from cdnjs before the inline bundle.
// 3. Writes the page in the Claude artifact format: no doctype, html, head or body tags (the host
//    wraps the file). Title, viewport-fit meta, fonts, tokens and styles come first, then the root
//    element, the pinned CDN scripts and the inline bundle.
//
// Usage: node scripts/build.mjs [--gen-only]

import * as esbuild from 'esbuild'
import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { LIGHT, DARK, STATIC } from '../src/ui/tokens.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const rel = (...p) => path.join(root, ...p)

const TITLE = 'Policy Engine Playground'
const CDN = [
  'https://cdnjs.cloudflare.com/ajax/libs/react/18.3.1/umd/react.production.min.js',
  'https://cdnjs.cloudflare.com/ajax/libs/react-dom/18.3.1/umd/react-dom.production.min.js',
  'https://cdnjs.cloudflare.com/ajax/libs/ethers/6.13.4/ethers.umd.min.js'
]
const FONTS =
  'https://fonts.googleapis.com/css2?family=DM+Sans:ital,wght@0,400;0,500;0,600;0,700;1,400&family=Geist+Mono:wght@400;500&display=swap'

// ---------------------------------------------------------------------------------------------
// 1. Content discovery
// ---------------------------------------------------------------------------------------------

async function listJson(dir) {
  let names = []
  try {
    names = (await readdir(rel(dir))).filter((n) => n.endsWith('.json')).sort()
  } catch {
    return []
  }
  const out = []
  for (const name of names) {
    try {
      const json = JSON.parse(await readFile(rel(dir, name), 'utf8'))
      out.push({ name, json })
    } catch (err) {
      console.warn(`warning: skipped ${dir}/${name}: ${err.message}`)
    }
  }
  return out
}

async function generateContent() {
  const scenarios = (await listJson('scenarios')).sort(
    (a, b) => (a.json.order ?? 0) - (b.json.order ?? 0) || a.name.localeCompare(b.name)
  )
  const challenges = (await listJson('challenges')).sort(
    (a, b) => (a.json.level ?? 0) - (b.json.level ?? 0) || a.name.localeCompare(b.name)
  )
  const lines = [
    '// Generated by scripts/build.mjs. Do not edit: run `npm run build` to refresh.',
    "import type { Challenge, Scenario } from '../../engine/types.ts'",
    ...scenarios.map((s, i) => `import s${i} from '../../../scenarios/${s.name}'`),
    ...challenges.map((c, i) => `import c${i} from '../../../challenges/${c.name}'`),
    '',
    `export const SCENARIOS: Scenario[] = [${scenarios.map((_, i) => `s${i}`).join(', ')}] as unknown as Scenario[]`,
    `export const CHALLENGES: Challenge[] = [${challenges.map((_, i) => `c${i}`).join(', ')}] as unknown as Challenge[]`,
    ''
  ]
  await mkdir(rel('src/ui/generated'), { recursive: true })
  const file = rel('src/ui/generated/content.ts')
  const next = lines.join('\n')
  let prev = ''
  try {
    prev = await readFile(file, 'utf8')
  } catch {}
  if (prev !== next) await writeFile(file, next)
  return { scenarios: scenarios.length, challenges: challenges.length }
}

// ---------------------------------------------------------------------------------------------
// 2. Bundle
// ---------------------------------------------------------------------------------------------

const GLOBALS = { react: 'React', 'react-dom': 'ReactDOM', 'react-dom/client': 'ReactDOM', ethers: 'ethers' }

/** Resolves react, react-dom and ethers to window globals, and react/jsx-runtime to a createElement shim. */
const globalsPlugin = {
  name: 'umd-globals',
  setup(build) {
    build.onResolve({ filter: /^(react|react-dom|react-dom\/client|ethers)$/ }, (args) => ({
      path: args.path,
      namespace: 'umd-global'
    }))
    build.onResolve({ filter: /^react\/jsx(-dev)?-runtime$/ }, (args) => ({ path: args.path, namespace: 'jsx-shim' }))
    build.onLoad({ filter: /.*/, namespace: 'umd-global' }, (args) => ({
      contents: `module.exports = window.${GLOBALS[args.path]};`,
      loader: 'js'
    }))
    build.onLoad({ filter: /.*/, namespace: 'jsx-shim' }, () => ({
      contents: [
        'var R = window.React;',
        'function jsx(type, props, key) {',
        '  return R.createElement(type, key === undefined ? props : Object.assign({}, props, { key: key }));',
        '}',
        'module.exports = { jsx: jsx, jsxs: jsx, jsxDEV: jsx, Fragment: R.Fragment };'
      ].join('\n'),
      loader: 'js'
    }))
  }
}

async function bundle() {
  const result = await esbuild.build({
    entryPoints: [rel('src/ui/main.tsx')],
    bundle: true,
    write: false,
    minify: true,
    format: 'iife',
    target: ['es2020'],
    jsx: 'automatic',
    legalComments: 'none',
    define: { 'process.env.NODE_ENV': '"production"' },
    plugins: [globalsPlugin],
    logLevel: 'warning'
  })
  return result.outputFiles[0].text
}

// ---------------------------------------------------------------------------------------------
// 3. Page
// ---------------------------------------------------------------------------------------------

const vars = (obj) =>
  Object.entries(obj)
    .map(([k, v]) => `--${k}:${v}`)
    .join(';')

async function styles() {
  const tokens = [
    `:root{${vars(STATIC)};${vars(LIGHT)};color-scheme:light}`,
    `@media (prefers-color-scheme: dark){:root:not([data-theme="light"]){${vars(DARK)};color-scheme:dark}}`,
    `:root[data-theme="dark"]{${vars(DARK)};color-scheme:dark}`
  ].join('\n')
  const css = await readFile(rel('src/ui/styles.css'), 'utf8')
  const min = await esbuild.transform(css, { loader: 'css', minify: true })
  return tokens + '\n' + min.code
}

/** Keeps the inline script from closing early or entering the HTML comment state. */
function escapeInline(js) {
  return js.replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--')
}

/** Runs the bundle only when the three libraries loaded; otherwise says what went wrong. */
function guarded(js) {
  const message =
    'The playground could not load its libraries from cdnjs.cloudflare.com. Check the connection and reload the page.'
  return [
    'if (window.React && window.ReactDOM && window.ethers) {',
    js,
    '} else {',
    `  var r = document.getElementById('root'); if (r) r.innerHTML = '<p class="boot">${message}</p>';`,
    '}'
  ].join('\n')
}

async function main() {
  const counts = await generateContent()
  console.log(`content: ${counts.scenarios} scenarios, ${counts.challenges} challenges`)
  if (process.argv.includes('--gen-only')) return

  const [js, css] = await Promise.all([bundle(), styles()])
  const html = [
    `<title>${TITLE}</title>`,
    '<meta name="claude:viewport-fit-sides" content="cover">',
    '<meta name="description" content="Set up a Safe with the Policy Engine, run a transaction and see step by step why it passes or is blocked.">',
    '<link rel="preconnect" href="https://fonts.googleapis.com">',
    '<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>',
    `<link rel="stylesheet" href="${FONTS}">`,
    `<style>\n${css}\n</style>`,
    '<div id="root"><p class="boot">Loading the Policy Engine Playground.</p></div>',
    ...CDN.map((src) => `<script src="${src}" crossorigin="anonymous"></script>`),
    `<script>\n${escapeInline(guarded(js))}\n</script>`,
    ''
  ].join('\n')

  await mkdir(rel('dist'), { recursive: true })
  const out = rel('dist/policy-playground.html')
  await writeFile(out, html)
  console.log(`wrote ${path.relative(process.cwd(), out)} (${(html.length / 1024).toFixed(1)} KB)`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
